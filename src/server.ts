import "dotenv/config";
import express from "express";
import helmet from "helmet";
import cors from "cors";
import rateLimit from "express-rate-limit";
import { api } from "./routes.js";
import { pool } from "./db.js";
const app=express();
app.disable("x-powered-by");
// Render terminates TLS and forwards the client IP in one trusted proxy hop.
app.set("trust proxy",1);
app.use(helmet({contentSecurityPolicy:false}));
const origins=(process.env.CORS_ORIGIN||"").split(",").map(x=>x.trim()).filter(Boolean);
app.use(cors({origin(o,cb){if(!o||origins.includes(o))return cb(null,true);cb(new Error("origin denied"));},methods:["GET","POST","PATCH"],allowedHeaders:["Content-Type","Authorization"]}));
app.use(express.json({limit:"30kb"}));
app.use("/api/public",rateLimit({windowMs:60000,max:60,standardHeaders:true,legacyHeaders:false}));
app.use("/api",api);
app.use(express.static("public"));
app.get("/health",(_q,r)=>r.json({ok:true}));
app.get("/health/db",async(_q,r)=>{try{await pool.query("SELECT 1");r.json({ok:true,database:true});}catch{r.status(503).json({ok:false,database:false});}});
app.use((e:any,_q:any,r:any,_n:any)=>{console.error("Request error",e?.message);r.status(500).json({error:"internal_error"});});
const port=Number(process.env.PORT||3000);
app.listen(port,()=>console.log("Clinic API on "+port));
